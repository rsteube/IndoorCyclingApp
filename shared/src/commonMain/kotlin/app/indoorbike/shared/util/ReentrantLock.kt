package app.indoorbike.shared.util

/**
 * A lock the thread holding it may take again: a method that holds it can call
 * another that takes it too. For state reached from several threads by callers
 * that expect a call to have taken effect when it returns, which a dispatcher
 * that the call hops onto cannot promise.
 */
expect class ReentrantLock() {
    fun lock()
    fun unlock()
}

inline fun <T> ReentrantLock.withLock(block: () -> T): T {
    lock()
    try {
        return block()
    } finally {
        unlock()
    }
}
