package app.indoorbike.shared.companion

import app.indoorbike.shared.ble.zwift.hmacSha256
import app.indoorbike.shared.util.secureRandomBytes

/**
 * How two devices recognise each other after the first time.
 *
 * ## What this is for, and what it is not
 *
 * The pairing code answers "may you drive this ride", once, for one ride, by
 * making a person read six characters off a screen. That is the right ceremony
 * for a stranger and the wrong one for the machine in the same room that the
 * rider has already trusted twenty times. This is the part that remembers.
 *
 * It buys **authentication**: a companion proves it is the one that was paired,
 * a port stops accepting anything that guesses a short code, and the identity
 * survives the address and port changing, which they do every ride. It does not
 * buy **confidentiality**. The socket is still plaintext, exactly as it was, so
 * anything on the network can still read a rider's watts. That is a deliberate
 * limit rather than an oversight, and it is written down here so nobody has to
 * infer it from the absence of an encrypt function.
 *
 * ## The scheme
 *
 * A shared secret, agreed once over the socket the pairing code already
 * authenticated, and then a mutual challenge-response over it:
 *
 *     app       -> challenge  nonceA
 *     companion -> proof      HMAC(key, "…:companion:" + nonceA + ":" + nonceC)
 *     app       -> welcome    HMAC(key, "…:app:"       + nonceA + ":" + nonceC)
 *
 * Both nonces are fresh per connection and both go into both proofs, so a
 * recording of yesterday's handshake proves nothing today. The two context
 * strings are what stop a companion replaying the app's own proof back at it:
 * the messages are different, so the tags are.
 *
 * ## Why HMAC-SHA256 and not something stronger
 *
 * Because a companion is somebody else's program, written in a game engine, and
 * the protocol is worth nothing if it cannot be implemented. HMAC-SHA256 is in
 * the standard library of every language and engine anyone would reach for.
 * X25519 is not: not in Godot, not in Python's standard library, not on Android
 * below API 28. A key agreement nobody can implement protects nobody.
 *
 * The cost is one window: an attacker already on the network, listening at the
 * exact moment of the one pairing, learns the key. Everything after that is
 * closed to them. Given the alternative was a permanently open port answering
 * to a six-character code, that is the trade this makes, on purpose.
 *
 * ## Hex, not base64
 *
 * Every value on the wire is lowercase hex. Slightly longer and impossible to
 * get subtly wrong: no alphabet variants, no padding rules, no url-safe
 * question. A companion author with `sha256` and a `for` loop can implement all
 * of this.
 */
object CompanionSecurity {

    /** Bytes in a pairing key. 256 bits, the natural size for an HMAC-SHA256 key. */
    const val KEY_BYTES = 32

    /** Bytes in a challenge nonce. 128 bits of freshness is past any birthday concern. */
    const val NONCE_BYTES = 16

    /**
     * Namespaced so a tag from this protocol can never be mistaken for one
     * from another, and versioned so a future scheme cannot be confused with
     * this one by an implementation that speaks both.
     */
    const val PROOF_PREFIX = "indoorbike-companion-v1"

    /** The companion proves itself with this context. */
    const val ROLE_COMPANION = "companion"

    /** And the app with this one, which is what stops a proof being reflected. */
    const val ROLE_APP = "app"

    /** A fresh pairing key, as hex. Generated by the app, once per companion. */
    fun newKeyHex(): String = secureRandomBytes(KEY_BYTES).toHex()

    /** A fresh challenge nonce, as hex. One per connection, per side. */
    fun newNonceHex(): String = secureRandomBytes(NONCE_BYTES).toHex()

    /**
     * The tag one side must present to prove it holds [keyHex].
     *
     * Both nonces appear in both proofs and always in the same order, so the
     * only thing separating the two messages is [role]. That is deliberate:
     * it is the smallest difference that makes reflection impossible, and it
     * is one string a companion author has to get right rather than an
     * ordering they have to notice.
     */
    fun proof(keyHex: String, role: String, nonceApp: String, nonceCompanion: String): String {
        // Fails closed. An unreadable key used to give an empty tag, and an
        // empty tag matches an empty proof, so a corrupt stored key let in
        // anybody who sent "proof": "". A key that cannot be read cannot be
        // proved, and the error says so rather than a comparison letting it by.
        val key = keyHex.hexToBytes()
            ?: throw IllegalArgumentException("not a pairing key")
        val message = PROOF_PREFIX + ":" + role + ":" + nonceApp + ":" + nonceCompanion
        return hmacSha256(key, message.encodeToByteArray()).toHex()
    }

    /**
     * True when [presented] is the tag [expected] should be.
     *
     * Compares in constant time with respect to the contents. An ordinary
     * string comparison returns on the first differing character, and the time
     * that takes is enough to recover a tag a byte at a time given enough
     * attempts. The length is allowed to leak: it is fixed by the protocol and
     * therefore not a secret.
     */
    fun proofMatches(expected: String, presented: String?): Boolean {
        if (expected.isEmpty()) return false
        if (presented == null || expected.length != presented.length) return false
        var difference = 0
        for (i in expected.indices) {
            difference = difference or (expected[i].code xor presented[i].code)
        }
        return difference == 0
    }

    /** True for a string that could be a key: the right length, and all hex. */
    fun looksLikeKey(hex: String?): Boolean =
        hex != null && hex.length == KEY_BYTES * 2 && hex.hexToBytes() != null

    /** True for a string that could be a nonce, on the same terms. */
    fun looksLikeNonce(hex: String?): Boolean =
        hex != null && hex.length == NONCE_BYTES * 2 && hex.hexToBytes() != null
}

/** Lowercase hex, two characters per byte. */
fun ByteArray.toHex(): String {
    val digits = "0123456789abcdef"
    val out = StringBuilder(size * 2)
    for (b in this) {
        val v = b.toInt() and 0xFF
        out.append(digits[v ushr 4]).append(digits[v and 0x0F])
    }
    return out.toString()
}

/**
 * The inverse, or null for anything that is not lowercase-or-uppercase hex of
 * even length. Null rather than an exception because every caller is parsing
 * something that arrived over a socket, where malformed is normal.
 */
fun String.hexToBytes(): ByteArray? {
    if (length % 2 != 0) return null
    val out = ByteArray(length / 2)
    for (i in out.indices) {
        val hi = this[i * 2].digitToIntOrNull(16) ?: return null
        val lo = this[i * 2 + 1].digitToIntOrNull(16) ?: return null
        out[i] = ((hi shl 4) or lo).toByte()
    }
    return out
}
